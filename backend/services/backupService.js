const { sequelize } = require("../config/mysqlDb");
const fs = require("fs");
const path = require("path");
const moment = require("moment");

/**
 * Custom MySQL Dumper using Sequelize
 * Generates a .sql file with CREATE TABLE and INSERT INTO statements.
 */
const exportMySQLToSQL = async () => {
  const backupsDir = path.join(process.cwd(), "backups");
  if (!fs.existsSync(backupsDir)) {
    fs.mkdirSync(backupsDir, { recursive: true });
  }
  const tempDir = path.join(backupsDir, "temp");
  if (!fs.existsSync(tempDir)) {
    fs.mkdirSync(tempDir, { recursive: true });
  }

  const fileName = `backup_${moment().format("YYYY-MM-DD_HH-mm-ss")}.sql`;
  const filePath = path.join(backupsDir, fileName);
  const writeStream = fs.createWriteStream(filePath);

  try {
    // 1. Get all tables
    const [tables] = await sequelize.query("SHOW TABLES");
    const dbName = sequelize.config.database;
    const tableKey = `Tables_in_${dbName}`;

    writeStream.write(`-- SQL Backup for ${dbName}\n`);
    writeStream.write(`-- Generated on: ${moment().format("LLLL")}\n\n`);
    writeStream.write(`SET FOREIGN_KEY_CHECKS = 0;\n\n`);

    for (const tableObj of tables) {
      const tableName = tableObj[tableKey];

      // 2. Get CREATE TABLE statement
      const [[createResult]] = await sequelize.query(`SHOW CREATE TABLE \`${tableName}\``);
      const createTableSql = createResult["Create Table"];
      writeStream.write(`-- Structure for table \`${tableName}\`\n`);
      writeStream.write(`DROP TABLE IF EXISTS \`${tableName}\`;\n`);
      writeStream.write(`${createTableSql};\n\n`);

      // 3. Get all data
      const [rows] = await sequelize.query(`SELECT * FROM \`${tableName}\``);
      if (rows.length > 0) {
        writeStream.write(`-- Data for table \`${tableName}\`\n`);
        
        // Split inserts into chunks of 100 to avoid huge single statements
        const chunkSize = 100;
        for (let i = 0; i < rows.length; i += chunkSize) {
          const chunk = rows.slice(i, i + chunkSize);
          const keys = Object.keys(chunk[0]);
          const columns = keys.map(k => `\`${k}\``).join(", ");
          
          const values = chunk.map(row => {
            const vals = keys.map(key => {
              const val = row[key];
              if (val === null) return "NULL";
              if (typeof val === "object" && !(val instanceof Date)) return sequelize.escape(JSON.stringify(val));
              if (typeof val === "string") return sequelize.escape(val);
              if (val instanceof Date) return sequelize.escape(moment(val).format("YYYY-MM-DD HH:mm:ss"));
              return sequelize.escape(val);
            });
            return `(${vals.join(", ")})`;
          }).join(",\n");

          writeStream.write(`INSERT INTO \`${tableName}\` (${columns}) VALUES\n${values};\n`);
        }
        writeStream.write(`\n`);
      }
    }

    writeStream.write(`SET FOREIGN_KEY_CHECKS = 1;\n`);
    writeStream.end();

    return {
      success: true,
      fileName,
      filePath,
      size: fs.statSync(filePath).size
    };
  } catch (error) {
    writeStream.end();
    if (fs.existsSync(filePath)) fs.unlinkSync(filePath);
    console.error("❌ Backup Error:", error);
    throw error;
  }
};

/**
 * List all local backups
 */
const listBackups = () => {
  const backupsDir = path.join(process.cwd(), "backups");
  if (!fs.existsSync(backupsDir)) return [];

  return fs.readdirSync(backupsDir)
    .filter(file => file.endsWith(".sql"))
    .map(file => {
      const stats = fs.statSync(path.join(backupsDir, file));
      return {
        fileName: file,
        size: stats.size,
        createdAt: stats.birthtime
      };
    })
    .sort((a, b) => b.createdAt - a.createdAt);
};

/**
 * Restore MySQL Database from a .sql file
 * @param {string} filePath 
 */
const restoreMySQLFromSQL = async (filePath) => {
  try {
    const sql = fs.readFileSync(filePath, "utf8");
    
    // Split by ;\n to get individual statements
    // This works reliably for files generated by exportMySQLToSQL
    const statements = sql.split(/;\s*\n/);

    // Disable logging for speed during restore
    const originalLogging = sequelize.options.logging;
    sequelize.options.logging = false;

    console.log(`🚀 Starting Database Restore: ${path.basename(filePath)}`);

    for (let statement of statements) {
      if (statement.trim()) {
        try {
          await sequelize.query(statement);
        } catch (err) {
          console.error("❌ Statement Error:", statement.substring(0, 100));
          console.error(err.message);
          // Continue or throw depending on severity (here we continue but log)
        }
      }
    }

    sequelize.options.logging = originalLogging;
    console.log("✅ Database Restore Completed");
    return true;
  } catch (error) {
    console.error("❌ Restore Error:", error);
    throw error;
  }
};

/**
 * Delete a backup
 */
const deleteBackup = (fileName) => {
  const filePath = path.join(process.cwd(), "backups", fileName);
  if (fs.existsSync(filePath)) {
    fs.unlinkSync(filePath);
    return true;
  }
  return false;
};

module.exports = {
  exportMySQLToSQL,
  listBackups,
  deleteBackup,
  restoreMySQLFromSQL
};
